<#
.SYNOPSIS
  Generate Smith & Griffiths Example 4 (homogeneous slope with free surface) p64 Q8 .dat.

.EXAMPLE
  powershell -File tools/gen_slope64_ex4_groundwater.ps1
  powershell -File tools/gen_slope64_ex4_groundwater.ps1 -Units us -CoordSmithNative -SrfLadder book4
  powershell -File tools/gen_slope64_ex4_groundwater.ps1 -GroundwaterStrength effective -GroundwaterUFactor 0.85
#>
[CmdletBinding()]
param(
    [string] $RepoRoot,
    [string] $OutPath,
    [ValidateSet('smith', 'book4', 'book', 'fine', 'extended')]
    [string] $SrfLadder = 'book4',
    [ValidateSet('metric', 'us')]
    [string] $Units = 'metric',
    [switch] $CoordSmithNative,
    [ValidateSet('effective', 'total')]
    [string] $GroundwaterStrength = 'effective',
    [double] $GroundwaterUFactor = 0.55
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if (-not $RepoRoot) {
    $RepoRoot = Resolve-Path (Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..')
}

$useSmithNative = $CoordSmithNative.IsPresent
if (-not $OutPath) {
    $suffix = if ($Units -eq 'us') { '_us_native' } elseif ($useSmithNative) { '_metric_native' } else { '' }
    $OutPath = Join-Path $RepoRoot "Verification\slope\Ex2_twolayerslope_groundwater\ex4_homogeneous_slope_groundwater$suffix.dat"
}

$genSrc = Join-Path $RepoRoot 'tools\gen_p64_q8_srf.ps1'
$lines = Get-Content $genSrc
$runLine = ($lines | Select-String -Pattern '^\$mesh = Build-Q8Mesh' | Select-Object -First 1).LineNumber
$funcStart = ($lines | Select-String -Pattern '^function Format-Double' | Select-Object -First 1).LineNumber
if (-not $runLine -or -not $funcStart) { throw "Could not locate sections in gen_p64_q8_srf.ps1" }
$funcBlock = ($lines[($funcStart - 1)..($runLine - 2)] -join "`n")
. ([scriptblock]::Create($funcBlock))

$ft2m = 0.3048
$psf2kPa = 0.04788025898
$pcf2kN_m3 = 9.81 / 62.4

$Nx1 = 21; $Nx2 = 12; $Ny1 = 5; $Ny2 = 5
$PhiDeg = 5.0
$PsiDeg = 0.0
$Nu = 0.3
$Tol = 0.0001; $Limit = 1000
$Kh = 0.0
$ExpectedFoS = 1.27
$ExpectedFoSTolerancePct = 3.9

if ($Units -eq 'us') {
    $W1 = 25.0; $S1 = 17.0; $W2 = 24.0; $H1 = 10.0; $H2 = 10.0
    $C_val = 200.0; $Gamma = 120.0; $E_val = 1.0e5; $GammaW = 62.4
    $unitsLabel = 'us (ft psf pcf gam_w=62.4)'
} else {
    $W1 = 25.0 * $ft2m; $S1 = 17.0 * $ft2m; $W2 = 24.0 * $ft2m
    $H1 = 10.0 * $ft2m; $H2 = 10.0 * $ft2m
    $C_val = 200.0 * $psf2kPa; $Gamma = 120.0 * $pcf2kN_m3
    $E_val = 1.0e5 * $psf2kPa; $GammaW = 9.81
    $unitsLabel = 'metric (m kN/m3 kPa)'
}

$surfFlatFt = @(
    0.0, -2.40, 2.0, -2.45, 4.0, -2.50, 6.0, -2.55, 8.0, -2.60,
    10.0, -2.67, 12.0, -2.80, 14.0, -2.95, 16.0, -3.15, 18.0, -3.40,
    20.0, -3.65, 22.0, -3.95, 24.0, -4.25, 26.0, -4.55, 28.0, -4.85,
    30.0, -5.30, 32.0, -5.70, 34.0, -6.25, 36.0, -6.85, 38.0, -7.65,
    40.0, -8.50, 67.0, -8.50
)

$surfPoints = New-Object 'System.Collections.Generic.List[object]'
for ($i = 0; $i -lt $surfFlatFt.Length; $i += 2) {
    $xFt = [double]$surfFlatFt[$i]
    $yFt = [double]$surfFlatFt[$i + 1]
    if ($Units -eq 'us') {
        $surfPoints.Add([pscustomobject]@{ X = $xFt; Y = $yFt }) | Out-Null
    } else {
        $surfPoints.Add([pscustomobject]@{ X = $xFt * $ft2m; Y = $yFt * $ft2m }) | Out-Null
    }
}

$SrfBook4 = @(0.5, 1.0, 1.25, 1.2656)
$SrfSmith = @(0.5, 1.0, 1.25, 1.2656, 1.30, 1.32, 1.34)
$SrfBook = @(1.0, 1.05, 1.10, 1.15, 1.20, 1.25, 1.30, 1.35, 1.40, 1.45, 1.50)
$SrfFine = @(1.20, 1.22, 1.24, 1.26, 1.28, 1.30, 1.32, 1.34, 1.36)
$SrfExtended = @(1.0, 1.05, 1.10, 1.15, 1.20, 1.25, 1.30, 1.35, 1.40, 1.45, 1.50,
    1.55, 1.60, 1.65, 1.70, 1.75, 1.80, 1.85, 1.90, 1.95, 2.0)
$SrfMulti = switch ($SrfLadder) {
    'book4' { $SrfBook4 }
    'smith' { $SrfSmith }
    'book' { $SrfBook }
    'extended' { $SrfExtended }
    default { $SrfFine }
}

function Write-P64DatWithGroundwater {
    param(
        [string] $Path,
        [hashtable] $Mesh,
        [double[]] $SrfList,
        [double] $PhiDeg,
        [double] $Cohesion,
        [double] $PsiDeg,
        [double] $Gamma,
        [double] $YoungsModulus,
        [double] $Nu,
        [double] $Tol,
        [int] $Limit,
        [string] $Title,
        [double] $Kh,
        [double] $GammaW,
        [object[]] $SurfPoints,
        [string] $UnitsLabel,
        [string] $GwStrength,
        [double] $GwUFactor,
        [double] $MeshCoordYOffset = 0
    )

    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('! <solver:p64>')
    [void]$sb.AppendLine("! $Title")
    [void]$sb.AppendLine('! Smith & Griffiths Example 4 - homogeneous slope with free surface')
    [void]$sb.AppendLine('! Generated by tools/gen_slope64_ex4_groundwater.ps1')
    [void]$sb.AppendLine("! units $UnitsLabel")
    [void]$sb.AppendLine('! <BEGIN:AnalysisOptions>')
    [void]$sb.AppendLine('! failure_criterion MohrCoulomb')
    [void]$sb.AppendLine('! material_type Isotropic')
    [void]$sb.AppendLine('! mesh_type Q8')
    [void]$sb.AppendLine('! mesh_source explicit')
    [void]$sb.AppendLine('! solver_executable SRF')
    [void]$sb.AppendLine("! embankment_nx1 $Nx1")
    [void]$sb.AppendLine("! embankment_nx2 $Nx2")
    [void]$sb.AppendLine("! embankment_ny1 $Ny1")
    [void]$sb.AppendLine("! embankment_ny2 $Ny2")
    [void]$sb.AppendLine("! embankment_w1 $(Format-Double $W1)")
    [void]$sb.AppendLine("! embankment_s1 $(Format-Double $S1)")
    [void]$sb.AppendLine("! embankment_w2 $(Format-Double $W2)")
    [void]$sb.AppendLine("! embankment_h1 $(Format-Double $H1)")
    [void]$sb.AppendLine("! embankment_h2 $(Format-Double $H2)")
    if ($MeshCoordYOffset -gt 0) {
        [void]$sb.AppendLine("! mesh_coord_y_offset $(Format-Double $MeshCoordYOffset)")
    }
    if ($useSmithNative) {
        [void]$sb.AppendLine('! groundwater_axis ydown')
    }
    [void]$sb.AppendLine('! srf_mode multi')
    [void]$sb.AppendLine("! groundwater_strength $GwStrength")
    if ($GwStrength -eq 'effective' -and [math]::Abs($GwUFactor - 1.0) -gt 1e-9) {
        [void]$sb.AppendLine("! groundwater_u_factor $(Format-Double $GwUFactor)")
    }
    [void]$sb.AppendLine("! k_h $(Format-Double $Kh)")
    [void]$sb.AppendLine('! fos_tol 0.05')
    [void]$sb.AppendLine("! expected_FoS $(Format-Double $ExpectedFoS)")
    [void]$sb.AppendLine("! expected_FoS_tolerance_pct $(Format-Double $ExpectedFoSTolerancePct)")
    [void]$sb.AppendLine('! expected_FoS_mode srf')
    [void]$sb.AppendLine('! <END:AnalysisOptions>')

    [void]$sb.AppendLine('! <BEGIN:Groundwater>')
    [void]$sb.AppendLine('! include true')
    [void]$sb.AppendLine("! gamma_w $(Format-Double $GammaW)")
    [void]$sb.AppendLine("! nosurf $($SurfPoints.Count)")
    [void]$sb.AppendLine('! surf')
    foreach ($pt in $SurfPoints) {
        [void]$sb.AppendLine("!   $(Format-Double $pt.X)  $(Format-Double $pt.Y)")
    }
    [void]$sb.AppendLine('! <END:Groundwater>')

    [void]$sb.AppendLine("$($Mesh.Nels)  $($Mesh.Nn)  1")
    [void]$sb.AppendLine("$(Format-Double $PhiDeg)  $(Format-Double $Cohesion)  $(Format-Double $PsiDeg)  $(Format-Double $Gamma)  $(Format-Double $YoungsModulus)  $(Format-Double $Nu)")

    for ($nid = 1; $nid -le $Mesh.Nn; $nid++) {
        $coord = $Mesh.DenseCoord[$nid]
        $cx = [double]$coord['X']
        $cy = [double]$coord['Y']
        [void]$sb.AppendLine("$(Format-Double $cx)  $(Format-Double $cy)")
    }

    foreach ($elem in $Mesh.Elems) {
        [void]$sb.AppendLine(("{0}  {1}  {2}  {3}  {4}  {5}  {6}  {7}" -f `
            $elem[0], $elem[1], $elem[2], $elem[3], $elem[4], $elem[5], $elem[6], $elem[7]))
    }

    [void]$sb.AppendLine($Mesh.BcRows.Count)
    foreach ($bc in $Mesh.BcRows) {
        [void]$sb.AppendLine(("{0}  {1}  {2}" -f $bc.Node, $bc.Fx, $bc.Fy))
    }

    [void]$sb.AppendLine("$(Format-Double $Tol)  $Limit")
    [void]$sb.AppendLine($SrfList.Count)
    [void]$sb.AppendLine(($SrfList | ForEach-Object { Format-Double $_ }) -join '  ')

    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [System.IO.File]::WriteAllText($Path, $sb.ToString().TrimEnd() + "`n")
    Write-Host "Wrote $Path  ($($Mesh.Nels) Q8, $($Mesh.Nn) nodes, nosurf=$($SurfPoints.Count), gw=$GwStrength u_factor=$GwUFactor)"
}

$mesh = Build-Q8Mesh -Nx1 $Nx1 -Nx2 $Nx2 -Ny1 $Ny1 -Ny2 $Ny2 -W1 $W1 -S1 $S1 -W2 $W2 -H1 $H1 -H2 $H2
$meshYOffset = 0.0
# Groundwater phreatic surface stays in Smith y-down native coords for the solver
# (embankment_* AnalysisOptions rebuild parametric mesh; Y-up offset applies to explicit coords only).
$surfPointsOut = $surfPoints

if ($useSmithNative) {
    # Smith y-down native: keep negative Y (no GUI offset).
} else {
    $meshYOffset = Set-MeshPositiveCoordinates -Mesh $mesh
}

$title = "Example 4: homogeneous slope GW ($UnitsLabel, explicit Q8, SrfLadder=$SrfLadder)"
Write-P64DatWithGroundwater -Path $OutPath -Mesh $mesh -SrfList $SrfMulti `
    -PhiDeg $PhiDeg -Cohesion $C_val -PsiDeg $PsiDeg -Gamma $Gamma -YoungsModulus $E_val -Nu $Nu `
    -Tol $Tol -Limit $Limit -Kh $Kh -GammaW $GammaW -SurfPoints $surfPointsOut `
    -UnitsLabel $unitsLabel -GwStrength $GroundwaterStrength -GwUFactor $GroundwaterUFactor `
    -MeshCoordYOffset $meshYOffset -Title $title
